from pydantic import BaseModel, Field


class SearchResult(BaseModel):
    """
    Output produced by the Search Agent.
    """

    topic: str = Field(
        description="Research topic"
    )

    findings: list[str] = Field(
        default_factory=list,
        description="Research findings"
    )

    source_count: int = Field(
        description="Number of sources reviewed"
    )


class SummaryResult(BaseModel):
    """
    Output produced by the Summarizer Agent.
    """

    summary: str = Field(
        description="Research summary"
    )

    key_points: list[str] = Field(
        default_factory=list,
        description="Key summary points"
    )

    confidence_score: float = Field(
        description="Confidence score of the summary"
    )


class ResearchReport(BaseModel):
    """
    Final structured report generated by
    the Research Assistant workflow.
    """

    topic: str = Field(
        description="Primary research topic"
    )

    executive_summary: str = Field(
        description="High-level summary of findings"
    )

    key_findings: list[str] = Field(
        default_factory=list,
        description="List of main findings"
    )

    sources_reviewed: list[str] = Field(
        default_factory=list,
        description="Sources used during research"
    )

    fact_check_notes: str = Field(
        description="Validation and consistency notes"
    )

    final_conclusion: str = Field(
        description="Final research conclusion"
    )